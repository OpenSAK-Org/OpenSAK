class TestCacheWpt:
    def test_element_order_like_gsak(self):
        note = SimpleNamespace(is_corrected=False, corrected_lat=None, corrected_lon=None, note="n")
        wpt = _wpts(generate_gpx([_cache(
            elevation=573.0, hidden_date=datetime(2022, 12, 13, tzinfo=timezone.utc),
            user_note=note,
        )]))[0]
        assert _tags(wpt) == [
            "ele", "time", "name", "desc", "url", "urlname", "sym", "type",
            "wptExtension", "cache",
        ]

    def test_elevation(self):
        assert "<ele>573.0</ele>" in generate_gpx([_cache(elevation=573)])
        assert "<ele>0.0</ele>" in generate_gpx([_cache(elevation=0.0)])  # sea level is known
        assert "<ele>" not in generate_gpx([_cache(elevation=None)])

    def test_elevation_missing_attribute(self):
        cache = _cache()
        del cache.elevation
        assert "<ele>" not in generate_gpx([cache])

    def test_desc_is_gsak_summary(self):
        gpx = generate_gpx([_cache(name="Ruhebank", placed_by="brenzo",
                                   difficulty=1.5, terrain=2.0)])
        assert "<desc>Ruhebank by brenzo (1.5/2)</desc>" in gpx

    def test_desc_without_owner(self):
        gpx = generate_gpx([_cache(name="Ruhebank", placed_by=None,
                                   difficulty=None, terrain=None)])
        assert "<desc>Ruhebank (1/1)</desc>" in gpx

    def test_urlname_is_name_by_owner(self):
        gpx = generate_gpx([_cache(name="Ruhebank", placed_by="brenzo")])
        assert "<urlname>Ruhebank by brenzo</urlname>" in gpx

    def test_macro_texts_still_win(self):
        text = ExportText(names={"GCBWND7": "Renamed"}, descriptions={"GCBWND7": "Macro desc"})
        gpx = generate_gpx([_cache(placed_by="brenzo")], text=text)
        assert "<desc>Macro desc</desc>" in gpx
        assert "<urlname>Renamed by brenzo</urlname>" in gpx
        assert "<groundspeak:name>Renamed</groundspeak:name>" in gpx

    def test_custom_waypoint_has_plain_desc_and_urlname(self):
        gpx = generate_gpx([_cache(cache_type="Parking Area", name="Car park")])
        assert "<desc>Car park</desc>" in gpx
        assert "<urlname>Car park</urlname>" in gpx

    def test_no_cmt_on_a_corrected_cache(self):
        note = SimpleNamespace(is_corrected=True, corrected_lat=47.3, corrected_lon=8.6, note=None)
        wpt = _wpts(generate_gpx([_cache(user_note=note)]))[0]
        assert wpt.find(f"{GPX}cmt") is None
        assert wpt.get("lat") == "47.300000"


