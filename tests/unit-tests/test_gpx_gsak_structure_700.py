def test_golden_ggz_index_offsets_point_at_each_cache_wpt():
    # GGZ shares the writer: the bigger <wpt> blocks must not shift the
    # index's file_pos/file_len off the cache's own <wpt>.
    caches = [_golden_cache(), _cache(gc_code="GC2ABCD", id=2, latitude=47.5, longitude=8.1)]
    with zipfile.ZipFile(io.BytesIO(generate_ggz(caches, filename="golden"))) as zf:
        gpx = zf.read("data/golden.gpx")
        index = ET.fromstring(zf.read("index/com/garmin/geocaches/v0/index.xml"))
    ns = {"g": "http://www.opencaching.com/xmlschemas/ggz/1/0"}
    entries = index.findall("g:file/g:gch", ns)
    assert [e.findtext("g:code", namespaces=ns) for e in entries] == ["GCBWND7", "GC2ABCD"]
    for e in entries:
        pos = int(e.findtext("g:file_pos", namespaces=ns))
        length = int(e.findtext("g:file_len", namespaces=ns))
        piece = gpx[pos:pos + length].decode("utf-8")
        assert piece.startswith("<wpt ") and piece.endswith("</wpt>")
        assert f"<name>{e.findtext('g:code', namespaces=ns)}</name>" in piece
    assert b"<bounds " in gpx


