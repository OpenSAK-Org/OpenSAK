# ── helpers ───────────────────────────────────────────────────────────────────

def _child(**kw) -> SimpleNamespace:
    values = dict(
        prefix="PK", wp_type="Parking Area", name="Parking", description=None,
        comment=None, latitude=47.1, longitude=8.5, url=None, wp_date=None,
        wp_code=None,
    )
    values.update(kw)
    return SimpleNamespace(**values)


def _tb(ref="TB1ABCD", name="Travel Bug", tracking_code="123456") -> SimpleNamespace:
    return SimpleNamespace(ref=ref, name=name, tracking_code=tracking_code)


def _cache(**kw) -> SimpleNamespace:
    values = dict(
        id=1, gc_code="GCBWND7", gc_cache_id=10572559, name="Early Birds",
        cache_type="Event Cache", latitude=47.19, longitude=8.52,
        difficulty=1.0, terrain=1.5, placed_by="Valentin", owner_name="Valentin",
        owner_id=6179840, available=True, archived=False, country="Switzerland",
        state="Zug", encoded_hints=None, hidden_date=None, logs=[], user_note=None,
        container="Other", short_description=None, short_desc_html=False,
        long_description="Long text", long_desc_html=True, attributes=[],
        waypoints=[], trackables=[], found=False, elevation=None,
    )
    values.update(kw)
    return SimpleNamespace(**values)


def _root(gpx: str) -> ET.Element:
    return ET.fromstring(gpx.split("\n", 1)[1])


def _wpts(gpx: str) -> list[ET.Element]:
    return _root(gpx).findall(f"{GPX}wpt")


def _tags(el: ET.Element) -> list[str]:
    return [c.tag.split("}")[1] if "}" in c.tag else c.tag for c in el]


# ── header ────────────────────────────────────────────────────────────────────

class TestHeader:
    def test_no_gpx_1_1_metadata_element(self):
        # <metadata> belongs to GPX 1.1; in a 1.0 file it made it invalid.
        assert "<metadata>" not in generate_gpx([_cache()])

    def test_header_elements_in_gpx_1_0_order(self):
        root = _root(generate_gpx([_cache()], filename="export"))
        head = [t for t in _tags(root) if t != "wpt"]
        assert head == ["name", "desc", "author", "time", "keywords", "bounds"]
        assert root.findtext(f"{GPX}name") == "export"
        assert root.findtext(f"{GPX}author") == "OpenSAK"
        assert root.findtext(f"{GPX}keywords") == "cache, geocache, groundspeak"

    def test_header_comes_before_the_first_wpt(self):
        tags = _tags(_root(generate_gpx([_cache(), _cache(gc_code="GC2", id=2)])))
        assert tags.index("bounds") < tags.index("wpt")

    def test_desc_marks_files_with_children(self):
        assert "<desc>Geocache file generated by OpenSAK (HasChildren)</desc>" in generate_gpx([_cache()])
        assert "<desc>Geocache file generated by OpenSAK</desc>" in generate_gpx(
            [_cache()], child_waypoints=False)

    def test_schema_location_and_namespaces(self):
        gpx = generate_gpx([_cache()])
        root_tag = gpx[gpx.index("<gpx"):gpx.index(">", gpx.index("<gpx"))]
        assert 'version="1.0"' in root_tag
        assert 'creator="OpenSAK"' in root_tag
        assert 'xmlns:xsd="http://www.w3.org/2001/XMLSchema"' in root_tag
        assert ('xsi:schemaLocation="http://www.topografix.com/GPX/1/0 '
                'http://www.topografix.com/GPX/1/0/gpx.xsd') in root_tag
        # groundspeak is still declared on each groundspeak:cache, not here.
        assert "xmlns:groundspeak" not in root_tag


# ── bounds ────────────────────────────────────────────────────────────────────

class TestBounds:
    def test_bounds_cover_caches_and_children(self):
        caches = [
            _cache(latitude=47.0, longitude=8.0,
                   waypoints=[_child(latitude=46.5, longitude=9.5)]),
            _cache(gc_code="GC2", id=2, latitude=48.0, longitude=7.0),
        ]
        assert gpx_bounds(caches) == (46.5, 7.0, 48.0, 9.5)
        assert ('<bounds minlat="46.500000" minlon="7.000000" '
                'maxlat="48.000000" maxlon="9.500000" />') in generate_gpx(caches)

    def test_bounds_use_the_exported_position(self):
        note = SimpleNamespace(is_corrected=True, corrected_lat=50.0, corrected_lon=10.0, note=None)
        caches = [_cache(latitude=47.0, longitude=8.0, user_note=note)]
        assert gpx_bounds(caches) == (50.0, 10.0, 50.0, 10.0)
        assert gpx_bounds(caches, use_corrected=False) == (47.0, 8.0, 47.0, 8.0)

    def test_bounds_without_children(self):
        caches = [_cache(latitude=47.0, longitude=8.0,
                         waypoints=[_child(latitude=46.0, longitude=9.0)])]
        assert gpx_bounds(caches, child_waypoints=False) == (47.0, 8.0, 47.0, 8.0)

    def test_bounds_skip_missing_coordinates(self):
        caches = [
            _cache(latitude=None, longitude=None),
            _cache(gc_code="GC2", latitude=47.0, longitude=8.0,
                   waypoints=[_child(latitude=None, longitude=None)]),
        ]
        assert gpx_bounds(caches) == (47.0, 8.0, 47.0, 8.0)

    def test_bounds_leave_out_the_0_0_placeholder(self):
        # A GSAK child waypoint without coordinates sits at 0/0. It is still
        # written, but GSAK's <bounds> leave it out, and so do OpenSAK's.
        caches = [_cache(latitude=47.0, longitude=8.0,
                         waypoints=[_child(latitude=0.0, longitude=0.0)])]
        assert gpx_bounds(caches) == (47.0, 8.0, 47.0, 8.0)
        assert len(_wpts(generate_gpx(caches))) == 2

    def test_no_bounds_for_an_empty_export(self):
        gpx = generate_gpx([])
        assert gpx_bounds([]) is None
        assert "<bounds" not in gpx
        _root(gpx)  # still well-formed

    def test_streamed_iterator_writes_the_bounds_it_is_given(self):
        # #1075: a streamed iterator can't be read twice, so the caller
        # passes the bounds computed from its selection.
        caches = [_cache(latitude=47.0, longitude=8.0)]
        buf = io.StringIO()
        write_gpx(buf, iter(caches), total=1, bounds=(1.0, 2.0, 3.0, 4.0))
        assert '<bounds minlat="1.000000" minlon="2.000000" maxlat="3.000000" maxlon="4.000000" />' \
            in buf.getvalue()


