def test_export_bounds_query(src_db):
    ids = [c.id for c in src_db]
    found = next(c for c in src_db if c.gc_code == "GCBWND7")
    other = next(c for c in src_db if c.gc_code == "GC2ABCD")
    # Caches at their export position (GCBWND7 corrected to 47.25/8.55,
    # GC2ABCD at 47.1/8.3) plus GCBWND7's children (46.9/8.4, 47.4/8.9).
    assert export_bounds(ids) == (46.9, 8.3, 47.4, 8.9)
    assert export_bounds(ids, child_waypoints=False) == (47.1, 8.3, 47.25, 8.55)
    assert export_bounds([found.id], use_corrected=False, child_waypoints=False) \
        == (47.19, 8.52, 47.19, 8.52)
    # Its children have no coordinates, or the 0/0 placeholder.
    assert export_bounds([other.id]) == (47.1, 8.3, 47.1, 8.3)
    assert export_bounds([]) is None


def test_gpx_bounds_of_database_caches_match_the_written_wpts(src_db):
    # gpx_bounds() measures database caches in the database; the result
    # must be the box around every <wpt> the export then writes.
    out_bounds = gpx_bounds(src_db)
    from opensak.db.database import reload_caches_full
    gpx = generate_gpx(reload_caches_full(src_db))
    points = [(float(w.get("lat")), float(w.get("lon"))) for w in _wpts(gpx)]
    assert (0.0, 0.0) in points   # written...
    lats, lons = zip(*(p for p in points if p != (0.0, 0.0)))   # ...but not in <bounds>
    assert out_bounds == (min(lats), min(lons), max(lats), max(lons))


