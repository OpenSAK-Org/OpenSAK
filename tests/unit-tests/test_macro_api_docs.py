"""The Lua API registry and the `opensak` table must agree, and the generated
files (docs/macros/api.md, macros/types/opensak.lua) must render.

Whether the committed files are up to date is deliberately not tested:
feature branches don't commit them, the Macro API docs workflow
(.github/workflows/macro-api-docs.yml) regenerates them after the merge to
beta. Check locally with: python scripts/generate_macro_api_docs.py --check
"""

from pathlib import Path

import pytest

from opensak.macro.api_docs import (
    EXAMPLES_DIR,
    GENERATED_FILES,
    render_api_markdown,
    render_lua_stub,
)

WORKFLOW = Path(__file__).resolve().parents[2] / ".github/workflows/macro-api-docs.yml"
from opensak.macro.runtime import (
    API,
    API_VERSION,
    FILTER_KEY_DOCS,
    FILTER_KEYS,
    MacroRuntime,
)


class _Host:
    """Just enough of a MacroHost to build the `opensak` table."""

    def clear_filter(self):
        pass

    def cache_count(self):
        return 0

    def end_macro(self):
        pass


def test_every_exposed_function_is_documented():
    out: list[str] = []
    MacroRuntime(_Host(), output=out.append).run(  # type: ignore[arg-type]
        "for name, value in pairs(opensak) do\n"
        "  if type(value) == 'table' then\n"
        "    for sub in pairs(value) do print(name .. '.' .. sub) end\n"
        "  else print(name) end\n"
        "end")
    assert sorted(out) == sorted(f.name for f in API)


def test_api_names_are_unique():
    names = [f.name for f in API]
    assert len(names) == len(set(names))


@pytest.mark.parametrize("func", API, ids=[f.name for f in API])
def test_api_entry_is_complete(func):
    assert func.signatures and all(s.startswith(f"opensak.{func.name}") for s in func.signatures)
    assert func.description.strip() and func.example.strip()
    assert 1 <= func.since <= API_VERSION
    for version, what in func.changed:
        assert func.since < version <= API_VERSION and what.strip()
    for p in (*func.params, *(q for form in func.overloads for q in form)):
        assert p.name and p.type and p.description.strip(), p
    if func.returns:
        assert all(part.strip() for part in func.returns)


@pytest.mark.parametrize("func", API, ids=[f.name for f in API])
def test_api_example_compiles(func):
    from lupa.lua54 import LuaRuntime

    LuaRuntime().compile(func.example)


def test_every_filter_key_is_documented():
    documented = [k for doc in FILTER_KEY_DOCS for k in doc.keys]
    assert sorted(documented) == sorted(FILTER_KEYS)


def test_api_markdown_lists_every_example(tmp_path):
    # Rendered from an explicit folder, not the working directory, so the
    # generator gives the same output wherever it runs (the docs workflow
    # must not open PRs for noise).
    for name in ("b_second.lua", "a_first.lua", "C_third.lua"):
        (tmp_path / name).write_text(f"-- {name} — does {name[0]}\n", encoding="utf-8")
    md = render_api_markdown(tmp_path)
    assert md == render_api_markdown(tmp_path)
    entries = [line for line in md.splitlines() if line.startswith("- [`") and ".lua`]" in line]
    assert [e.split("`")[1] for e in entries] == ["C_third.lua", "a_first.lua", "b_second.lua"]
    assert all(EXAMPLES_DIR.as_posix() in e for e in entries)


def _workflow_add_paths() -> list[str]:
    lines = WORKFLOW.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(lines) if line.strip() == "add-paths: |")
    indent = len(lines[start + 1]) - len(lines[start + 1].lstrip())
    paths = []
    for line in lines[start + 1:]:
        if not line.strip() or len(line) - len(line.lstrip()) < indent:
            break
        paths.append(line.strip())
    return paths


@pytest.mark.parametrize("path", [p for p, _ in GENERATED_FILES], ids=lambda p: p.name)
def test_docs_workflow_commits_every_generated_file(path):
    # A generated file outside add-paths would be regenerated by the
    # workflow but never committed.
    target = path.as_posix()
    add_paths = _workflow_add_paths()
    assert any(target == p or (p.endswith("/") and target.startswith(p)) for p in add_paths), \
        f"{target} is not under add-paths in {WORKFLOW.name}: {add_paths}"


def test_lua_stub_compiles():
    from lupa.lua54 import LuaRuntime

    LuaRuntime().compile(render_lua_stub())
