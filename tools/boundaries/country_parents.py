#!/usr/bin/env python3
"""
tools/boundaries/country_parents.py

Regenerate src/opensak/geo/country_parents.py — which countries each
state / county `parent` code in OpenSAK-Data belongs to (issue #1379).

boundaries.db names countries but gives them no code, while states and
counties carry their country as a `parent` code ("aut", "deu", ...). The
reverse geocoder needs the link to reject a state or county that doesn't
belong to the country it found. Rather than a hand-written name→ISO table
that drifts from the data, this script derives it from the data itself:
for every parent code it takes a point inside each of its states (or its
counties, for codes without states) and records which country polygons the
point lies in. Every country that gets a point is kept, most points first:
a code can legitimately span several countries in the data (e.g. "chn"
states in Hong Kong, Macao and Taiwan, or old "sdn" states in South Sudan),
and the resolver must not reject those.

Run it whenever an OpenSAK-Data release adds or changes countries, states
or counties (e.g. a new country from osm_extract.py), and commit the
regenerated module. Until then, regions with a parent code the module
doesn't know are simply never rejected.

Usage:
    tools/boundaries/country_parents.py                 # fetch the published baseline
    tools/boundaries/country_parents.py --data-dir DIR  # a local pre-publish directory

DIR is a boundaries directory (boundaries.db + countries/ + states/ +
counties/). Without --data-dir, the baseline is downloaded into a temporary
directory first. County packs that are missing are downloaded on demand.
"""

from __future__ import annotations

import argparse
import collections
import sys
import tempfile
from pathlib import Path

from shapely.geometry import shape
from shapely.strtree import STRtree

from opensak.geo.packs import fetch_baseline
from opensak.geo.store import BoundaryStore

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src" / "opensak" / "geo" / "country_parents.py"


def _shape(geometry: dict):
    shp = shape(geometry)
    return shp if shp.is_valid else shp.buffer(0)


def derive(store: BoundaryStore) -> dict[str, collections.Counter]:
    """Return parent code → Counter of the countries its regions lie in."""
    names: list[str] = []
    geoms = []
    for region, _box in store.regions_with_boxes("country"):
        names.append(region.name)
        geoms.append(_shape(store.geometry("country", region)))
    tree = STRtree(geoms)

    votes: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)

    def vote(layer: str, region) -> None:
        if not region.parent:
            return
        try:
            point = _shape(store.geometry(layer, region)).representative_point()
        except FileNotFoundError:
            print(f"  skipped {layer} {region.name!r}: pack {region.pack} not available")
            return
        # Every country polygon containing the point counts: where country
        # polygons overlap (e.g. San Marino inside an Italy without a hole),
        # the resolver may report either, and both must accept the region.
        for name in {names[i] for i in tree.query(point, predicate="within")}:
            votes[region.parent][name] += 1

    state_parents: set[str] = set()
    for region, _box in store.regions_with_boxes("state"):
        state_parents.add(region.parent)
        vote("state", region)
    # Codes that only have counties (no state layer) vote with their counties.
    for region, _box in store.regions_with_boxes("county"):
        if region.parent and region.parent not in state_parents:
            vote("county", region)

    return {code: counts for code, counts in votes.items() if counts}


def render(votes: dict[str, collections.Counter], dataset: str | None) -> str:
    lines = [
        "# src/opensak/geo/country_parents.py — which country each state/county",
        "# parent code belongs to (issue #1379).",
        "#",
        "# GENERATED by tools/boundaries/country_parents.py — do not edit by hand.",
        f"# Source: OpenSAK-Data dataset v{dataset if dataset is not None else '?'}.",
        "",
        "from __future__ import annotations",
        "",
        f"DATASET_VERSION: str | None = {dataset!r}",
        "",
        "# parent code (as in region_state / region_county) → the countries its",
        "# regions lie in (names as in region_country / world.geojson), most first",
        "PARENT_COUNTRIES: dict[str, tuple[str, ...]] = {",
    ]
    for code in sorted(votes):
        names = tuple(name for name, _n in votes[code].most_common())
        lines.append(f"    {code!r}: {names!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--data-dir", type=Path,
                        help="boundaries directory (default: download into a temp dir)")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    with tempfile.TemporaryDirectory() as tmp:
        data_dir = args.data_dir or Path(tmp)
        if not (data_dir / "boundaries.db").is_file():
            print(f"Downloading the boundary baseline into {data_dir} …")
            if not fetch_baseline(data_dir):
                print("Could not download the boundary baseline", file=sys.stderr)
                return 1

        store = BoundaryStore(data_dir)
        try:
            votes = derive(store)
            dataset = store.dataset_version()
        finally:
            store.close()

    for code in sorted(votes):
        if len(votes[code]) > 1:
            print(f"  {code} spans several countries: {dict(votes[code].most_common())}")

    args.output.write_text(render(votes, dataset), encoding="utf-8")
    print(f"Wrote {len(votes)} parent codes to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
